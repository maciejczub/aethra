<#
.SYNOPSIS
    Creates the "Aethra" and "Aethra panel" desktop shortcuts and, optionally, starts Aethra
    automatically after logging in.

.DESCRIPTION
    Run from the Aethra folder (the one that contains Aethra.cmd):

        powershell -ExecutionPolicy Bypass -File scripts\install-shortcuts.ps1
        powershell -ExecutionPolicy Bypass -File scripts\install-shortcuts.ps1 -Autostart -DelaySeconds 20
        powershell -ExecutionPolicy Bypass -File scripts\install-shortcuts.ps1 -RemoveAutostart

    Autostart uses a shortcut in the user's Startup folder (no administrator
    rights needed). The delay gives Windows time to bring up the displays and
    network adapters before the show starts.
#>
[CmdletBinding()]
param(
    [string]$AethraDir = "",
    [string]$Config = "show.yaml",
    [switch]$Autostart,
    [int]$DelaySeconds = 20,
    [switch]$RemoveAutostart
)

$ErrorActionPreference = "Stop"

if (-not $AethraDir) {
    # The script lives in <Aethra>\scripts (bundle) or <repo>\scripts\windows (checkout).
    $AethraDir = Split-Path -Parent $PSScriptRoot
    if (-not (Test-Path (Join-Path $AethraDir "Aethra.cmd"))) {
        $AethraDir = Split-Path -Parent $AethraDir
    }
}
$AethraDir = (Resolve-Path $AethraDir).Path
$Launcher = Join-Path $AethraDir "Aethra.cmd"
if (-not (Test-Path $Launcher)) {
    $Launcher = Join-Path $AethraDir "scripts\windows\Aethra.cmd"
}
if (-not (Test-Path $Launcher)) {
    throw "Aethra.cmd not found in $AethraDir"
}

$Shell = New-Object -ComObject WScript.Shell

function New-Shortcut([string]$Path, [string]$Target, [string]$Arguments, [string]$WorkDir) {
    $Link = $Shell.CreateShortcut($Path)
    $Link.TargetPath = $Target
    $Link.Arguments = $Arguments
    $Link.WorkingDirectory = $WorkDir
    $Link.WindowStyle = 1
    $Link.Description = "Aethra stage video player"
    $Icon = Join-Path $AethraDir "aethra.ico"
    if (-not (Test-Path $Icon)) { $Icon = Join-Path $AethraDir "gfx\aethra.ico" }
    if (Test-Path $Icon) { $Link.IconLocation = "$Icon,0" }
    $Link.Save()
    Write-Host "created $Path"
}

$Desktop = [Environment]::GetFolderPath("Desktop")
New-Shortcut (Join-Path $Desktop "Aethra.lnk") $Launcher "`"$Config`"" $AethraDir
# The control panel: edit the show, run the checks and tools, start and watch the show.
$PanelLink = Join-Path $Desktop "Aethra panel.lnk"
New-Shortcut $PanelLink $Launcher "gui `"$Config`"" $AethraDir
$Link = $Shell.CreateShortcut($PanelLink); $Link.WindowStyle = 7; $Link.Save()  # minimised: the launcher only starts the panel

$Startup = [Environment]::GetFolderPath("Startup")
$StartupLink = Join-Path $Startup "Aethra.lnk"
$AutostartCmd = Join-Path $AethraDir "Aethra-autostart.cmd"

if ($RemoveAutostart) {
    Remove-Item -Force -ErrorAction SilentlyContinue $StartupLink, $AutostartCmd
    Write-Host "autostart removed"
}
elseif ($Autostart) {
    $Body = @(
        "@echo off",
        "rem Generated by install-shortcuts.ps1: waits for displays and network, then starts the show.",
        "set AETHRA_START_DELAY=$DelaySeconds",
        "call `"$Launcher`" `"$Config`""
    )
    Set-Content -Path $AutostartCmd -Value $Body -Encoding ASCII
    New-Shortcut $StartupLink $AutostartCmd "" $AethraDir
    Write-Host "Aethra will start $DelaySeconds s after logging in."
}
